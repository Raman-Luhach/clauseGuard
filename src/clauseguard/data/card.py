"""Data cards: statistics about a module's unit table, written to data/data_cards/<module>.md."""

from __future__ import annotations

import json
from collections.abc import Callable

import numpy as np
import pandas as pd

from clauseguard.config import ModuleConfig, load_module_config
from clauseguard.data.units import SPLITS, UNKNOWN_DOC, label_matrix, load_units
from clauseguard.paths import data_cards_dir

# Module-specific sections: fn(units) -> (markdown lines, stats)
Extras = Callable[[pd.DataFrame], tuple[list[str], dict]]


def md_table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines


def _token_lengths(cfg: ModuleConfig, texts: pd.Series) -> tuple[str, np.ndarray] | None:
    checkpoints = [m.checkpoint for m in cfg.models.values() if m.type == "transformer"]
    if not checkpoints:
        return None
    try:
        from transformers import AutoTokenizer

        tokenizer = AutoTokenizer.from_pretrained(checkpoints[-1])
    except Exception:  # offline, or transformers not installed
        return None
    from transformers.utils import logging as hf_logging

    previous = hf_logging.get_verbosity()
    hf_logging.set_verbosity_error()  # measuring full lengths on purpose; no truncation warning
    try:
        ids = tokenizer(texts.tolist(), add_special_tokens=True, truncation=False)["input_ids"]
    finally:
        hf_logging.set_verbosity(previous)
    return checkpoints[-1], np.array([len(x) for x in ids])


def build_card(module: str, extras: Extras | None = None) -> tuple[str, dict]:
    cfg = load_module_config(module)
    df = load_units(module)
    y = label_matrix(df["labels"], cfg.label_ids)
    stats: dict = {"module": module, "unit_type": cfg.unit_type, "n_units": len(df)}
    md = [f"# Data card: {cfg.display_name} (`{module}`)", ""]
    md += [f"Unit type: **{cfg.unit_type}**. Generated by `clauseguard data card {module}`.", ""]

    md += ["## Splits", ""]
    rows = []
    for split in SPLITS:
        part = df[df["split"] == split]
        mask = (df["split"] == split).to_numpy()
        docs = part.loc[part["doc_id"] != UNKNOWN_DOC, "doc_id"].nunique()
        no_label = float((y[mask].sum(1) == 0).mean()) if mask.any() else 0.0
        multi = int((y[mask].sum(1) > 1).sum())
        rows.append([split, len(part), docs, f"{no_label:.1%}", multi])
        stats[split] = {
            "units": len(part),
            "documents": docs,
            "no_label": no_label,
            "multi_label": multi,
        }
    md += md_table(
        ["split", "units", "documents", "units with no label", "multi-label units"], rows
    )

    md += ["", "## Labels", ""]
    rows = []
    stats["labels"] = {}
    for j, label in enumerate(cfg.labels):
        counts = [int(y[(df["split"] == s).to_numpy(), j].sum()) for s in SPLITS]
        rows.append([f"`{label.id}`", label.source, *counts])
        stats["labels"][label.id] = dict(zip(SPLITS, counts, strict=True))
    md += md_table(["label", "source name", *SPLITS], rows)

    md += ["", "## Length", ""]
    words = df["text"].str.split().str.len()
    q = words.quantile([0.5, 0.9, 0.95]).to_dict()
    md.append(
        f"Words per unit: median {q[0.5]:.0f}, 90th percentile {q[0.9]:.0f}, "
        f"95th percentile {q[0.95]:.0f}, max {words.max()}."
    )
    stats["words"] = {"median": q[0.5], "p90": q[0.9], "p95": q[0.95], "max": int(words.max())}
    tokens = _token_lengths(cfg, df["text"])
    if tokens is not None:
        checkpoint, lengths = tokens
        over = float((lengths > cfg.max_length).mean())
        md.append(
            f"Tokens ({checkpoint}): median {np.median(lengths):.0f}, 95th percentile "
            f"{np.percentile(lengths, 95):.0f}, max {lengths.max()}; **{over:.2%} of units exceed "
            f"max_length = {cfg.max_length}** and are truncated."
        )
        stats["tokens"] = {
            "checkpoint": checkpoint,
            "over_max_length": over,
            "max": int(lengths.max()),
        }

    md += ["", "## Duplicates", ""]
    train_texts = set(df.loc[df["split"] == "train", "text"])
    dup_train = int(df.loc[df["split"] == "train", "text"].duplicated().sum())
    md.append(f"Exact duplicates inside train: {dup_train}.")
    for split in ("validation", "test"):
        texts = df.loc[df["split"] == split, "text"]
        shared = int(texts.isin(train_texts).sum())
        md.append(
            f"{split.capitalize()} units whose exact text also appears in train: "
            f"{shared} ({shared / max(len(texts), 1):.1%})."
        )
        stats[f"{split}_in_train"] = shared
    md.append("Documents never cross splits (checked when the table is built).")

    if extras is not None:
        extra_md, extra_stats = extras(df)
        md += ["", *extra_md]
        stats.update(extra_stats)

    out = data_cards_dir()
    out.mkdir(parents=True, exist_ok=True)
    text = "\n".join(md) + "\n"
    (out / f"{module}.md").write_text(text, encoding="utf-8")
    (out / f"{module}.json").write_text(
        json.dumps(stats, indent=2, default=float), encoding="utf-8"
    )
    return text, stats
